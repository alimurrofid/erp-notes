#!/usr/bin/env node
/**
 * generate-lesson-order.mjs — derives the reading order used by LessonNav.
 *
 * Order rules:
 *   1. root index
 *   2. each section in numeric order: section index, then the internal links in
 *      the order they appear on that index, then any remaining files sorted.
 *   3. nested software indexes are expanded the same way.
 *
 * Usage:
 *   node .agents/scripts/generate-lesson-order.mjs          # write
 *   node .agents/scripts/generate-lesson-order.mjs --check  # fail if stale
 */

import fs from "node:fs"
import path from "node:path"

const ROOT = path.resolve("content")
const OUT = path.resolve("quartz/generated/lessonOrder.ts")
const CHECK = process.argv.includes("--check")

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (full.endsWith(".md")) out.push(full)
  }
  return out
}

const files = walk(ROOT)
const rel = (file) => path.relative(ROOT, file).split(path.sep).join("/")
const slugOf = (file) => rel(file).replace(/\.md$/, "")
const bySlug = new Map(files.map((file) => [slugOf(file), file]))

function linksIn(slug) {
  const file = bySlug.get(slug)
  if (!file) return []
  const text = fs.readFileSync(file, "utf8")
  const out = []
  for (const match of text.matchAll(/\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]/g)) {
    const target = match[1].trim()
    if (bySlug.has(target)) out.push(target)
  }
  return out
}

const sections = [...new Set([...bySlug.keys()].map((slug) => slug.split("/")[0]))]
  .filter((segment) => /^\d+-/.test(segment))
  .sort((a, b) => Number.parseInt(a, 10) - Number.parseInt(b, 10))

const order = []
const seen = new Set()

function add(slug) {
  if (!bySlug.has(slug) || seen.has(slug)) return
  seen.add(slug)
  order.push(slug)
}

function addWithChildren(slug) {
  add(slug)
  if (!slug.endsWith("/index")) return
  for (const target of linksIn(slug)) {
    if (target.startsWith(`${slug.slice(0, -"/index".length)}/`)) addWithChildren(target)
  }
}

add("index")

for (const section of sections) {
  const indexSlug = `${section}/index`
  addWithChildren(indexSlug)

  for (const target of linksIn(indexSlug)) {
    if (target.startsWith(`${section}/`)) addWithChildren(target)
  }

  const remaining = [...bySlug.keys()]
    .filter((slug) => slug.startsWith(`${section}/`) && !seen.has(slug))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }))
  for (const slug of remaining) add(slug)
}

// Any file not reachable from a section index (e.g. a new section) is appended
// in stable order so navigation never loses a page.
for (const slug of [...bySlug.keys()].sort()) add(slug)

const content = `// Generated by .agents/scripts/generate-lesson-order.mjs. Do not edit by hand.
export const LESSON_ORDER: string[] = [
${order.map((slug) => `  ${JSON.stringify(slug)},`).join("\n")}
]
`

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
  if (current !== content) {
    console.error("Lesson order is stale. Run: npm run lesson-order")
    process.exit(1)
  }
  console.log(`Lesson order is current (${order.length} pages).`)
  process.exit(0)
}

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, content, "utf8")
console.log(`Wrote ${order.length} pages to ${path.relative(process.cwd(), OUT)}`)
